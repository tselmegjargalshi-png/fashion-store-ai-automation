export function getProductsBySlugs(slugs: string[]) {
  return slugs.map((s) => getProductBySlug(s)).filter((p): p is Product => Boolean(p));
}

export function getRelatedProducts(product: Product, limit = 4) {
  const sameCategory = PRODUCTS.filter((p) => p.category === product.category && p.id !== product.id);
  const others = PRODUCTS.filter((p) => p.category !== product.category).sort((a, b) => b.popularity - a.popularity);
  return [...sameCategory, ...others].slice(0, limit);
}

export function getAllColors(): ColorOption[] {
  const map = new Map<string, ColorOption>();
  PRODUCTS.forEach((p) => p.colors.forEach((c) => map.set(c.name, c)));
  return [...map.values()];
}
